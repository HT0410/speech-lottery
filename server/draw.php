    $counts = [];
    foreach ($odaiList as $o) {
        $counts[$o['cat']] = ($counts[$o['cat']] ?? 0) + 1;
    }
    echo json_encode([
        'total' => count($odaiList),
        'byCategory' => $counts,
    ], JSON_UNESCAPED_UNICODE);
    exit;
}

$requestedCat = $_GET['cat'] ?? '';
$requestedCat = is_string($requestedCat) ? trim($requestedCat) : '';

$pool = ($requestedCat === '' || $requestedCat === 'すべて')
    ? $odaiList
    : array_values(array_filter($odaiList, fn($o) => $o['cat'] === $requestedCat));

if (empty($pool)) {
    http_response_code(400);
    echo json_encode(['error' => 'invalid category'], JSON_UNESCAPED_UNICODE);
    exit;
}

